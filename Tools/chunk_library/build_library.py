"""Turns chunkgen.py's output into the mod's chunk library:
Game/creative_chunk_lib_NN.lua, plain Lua data the game loads by itself.

    creative_chunk_lib = creative_chunk_lib or {}
    local L = creative_chunk_lib
    L["XAR_FOO"]="<sample>|<sample>|..."

One sample per different result the game's generator gave in different
contexts (a type without randomness has one). A sample is
    <palette>;<cells>;<ents>;<monsters>
  palette  = block names, comma separated
  cells    = the 4096 cells, index x*256 + y*16 + z (z fastest), run-length
             tokens "v" or "<count>x<v>", v = 0-based palette index (air is
             kept as its block name; the mod decides what is air)
  ents     = interactables "x:y:z:type:param" separated by "/" (cell coords)
  monsters = "x:y:z:type" separated by "/" (chunk coords, floats)
Reads Output/chunk_library/chunks.jsonl (v1: blocks only, one sample) and then
chunks_v2.jsonl (samples + ents), the later one winning per type.
    python build_library.py
"""
import json, os, glob

HERE = os.path.dirname(os.path.abspath(__file__))
MOD = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.abspath(os.path.join(MOD, "..", "..", "..", "Output", "chunk_library"))
SOURCES = [os.path.join(OUT, "chunks.jsonl"), os.path.join(OUT, "chunks_v2.jsonl")]
FILE_FMT = os.path.join(MOD, "Game", "creative_chunk_lib_%02d.lua")
FILE_MAX = 1_000_000            # bytes of data per file


def ok_name(s):
    return bool(s) and all(c.isalnum() or c == "_" for c in s)


def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def check_cells(name, pal, rle):
    total = 0
    for tok in rle.split(","):
        n, _, v = tok.partition("x")
        total += int(n) if v else 1
        assert int(v or n) < len(pal), name
    assert total == 4096, (name, total)
    for nm in pal:
        assert ok_name(nm), (name, nm)


def sample_str(name, s):
    check_cells(name, s["pal"], s["rle"])
    ents = [e for e in s.get("bents", []) if ok_name(e[3])]
    mons = [m for m in s.get("ments", []) if ok_name(m[3])]
    return ";".join([
        ",".join(s["pal"]),
        s["rle"],
        "/".join("%d:%d:%d:%s:%d" % (e[0], e[1], e[2], e[3], e[4]) for e in ents),
        "/".join("%s:%s:%s:%s" % (num(m[0]), num(m[1]), num(m[2]), m[3]) for m in mons),
    ])


def main():
    entries, stats = {}, {"multi": 0, "ents": 0, "mons": 0}
    for src in SOURCES:
        if not os.path.exists(src):
            continue
        with open(src, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                it = json.loads(line)
                if "error" in it:
                    continue
                samples = it.get("samples") or [{"pal": it["pal"], "rle": it["rle"]}]
                entries[it["name"]] = "|".join(sample_str(it["name"], s) for s in samples)
    for v in entries.values():
        parts = v.split("|")
        stats["multi"] += len(parts) > 1
        stats["ents"] += any(p.split(";")[2] for p in parts)
        stats["mons"] += any(p.split(";")[3] for p in parts)

    for old in glob.glob(FILE_FMT.replace("%02d", "*")):
        os.remove(old)
    head = ("-- Creative Menu chunk library (generated by Tools/chunk_library: the game's own\n"
            "-- generators run for every built-in block type). Data only - see game_creative_chunklib.lua.\n"
            "creative_chunk_lib = creative_chunk_lib or {}\nlocal L = creative_chunk_lib\n")
    files, buf, size = [], [], 0
    for name in sorted(entries):
        line = 'L["%s"]="%s"\n' % (name, entries[name])
        if buf and size + len(line) > FILE_MAX:
            files.append(buf)
            buf, size = [], 0
        buf.append(line)
        size += len(line)
    if buf:
        files.append(buf)
    total = 0
    for i, lines in enumerate(files, 1):
        with open(FILE_FMT % i, "w", encoding="utf-8", newline="\n") as f:
            f.write(head)
            f.writelines(lines)
        total += os.path.getsize(FILE_FMT % i)
    print(f"{len(entries)} block types ({stats['multi']} with several samples, {stats['ents']} with "
          f"interactables, {stats['mons']} with monsters) -> {len(files)} files, {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
